export function translateFocusString(text, lang) {
  if (!text) return "";
  if (lang !== "en") return text;
  return text.replace(/\b[a-zA-ZäöüÄÖÜß-]+\b/g, (token) => {
    const lower = token.toLowerCase();
    if (FOCUS_MAP[lower]) return FOCUS_MAP[lower];
    if (token.includes("-")) {
      return token
        .split("-")
        .map((p) => FOCUS_MAP[p.toLowerCase()] || p)
        .join(" ");
    }
    return token;
  });
}

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const stored = localStorage.getItem(STORAGE_KEY);
    return stored === "en" || stored === "de" ? stored : "de";
  });

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const value = {
    lang,
    setLang: setLangState,
    t: (key, vars) => interpolate(DICTS[lang][key] ?? key, vars),
    category: (name) => (lang === "en" ? CATEGORY_EN[name] || name : name),
    equipment: (name) => (lang === "en" ? EQUIPMENT_EN[name] || name : name),
    split: (name) => (lang === "en" ? SPLIT_EN[name] || name : name),
    weekday: (name) => (lang === "en" ? WEEKDAY_EN[name] || name : name),
    focusText: (text) => translateFocusString(text, lang),
    exerciseName: (ex) => {
      if (!ex) return "";
      const deName = typeof ex === "string" ? ex : ex.name;
      if (lang === "en") {
        return (typeof ex === "object" && ex.nameEn) || deName;
      }
      return deName;
    },
    locale: lang === "en" ? "en-GB" : "de-DE",
  };

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n muss innerhalb von I18nProvider verwendet werden");
  return ctx;
}
